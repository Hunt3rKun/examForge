#!/usr/bin/env bash
# Writes the EXAMFORGE_TEST_* environment file consumed by
# ./scripts/verify-integration.sh --env-file <file>.
#
# Nothing is sent anywhere and no value is printed: the script only collects
# inputs and writes one local file with mode 0600. The file is git-ignored
# (.env.* in .gitignore) and must never be committed.
#
# Usage:
#   ./scripts/setup-integration-env.sh                 # writes .env.integration
#   ./scripts/setup-integration-env.sh /path/to/file   # writes elsewhere
#   ./scripts/setup-integration-env.sh --force ...     # overwrite an existing file
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

force=0
out=".env.integration"
for arg in "$@"; do
  case "$arg" in
    --force) force=1 ;;
    -h|--help) sed -n '2,12p' "${BASH_SOURCE[0]}"; exit 0 ;;
    -*) printf 'setup-integration-env: unknown option: %s\n' "$arg" >&2; exit 1 ;;
    *) out="$arg" ;;
  esac
done

fail() { printf 'setup-integration-env: %s\n' "$1" >&2; exit 1; }

if [[ -e "$out" && $force -ne 1 ]]; then
  fail "$out already exists; pass --force to overwrite"
fi

# ask VAR "prompt" "default"
ask() {
  local __var="$1" __prompt="$2" __default="${3:-}" __reply=""
  if [[ -n "$__default" ]]; then
    read -r -p "$__prompt [$__default]: " __reply || true
    __reply="${__reply:-$__default}"
  else
    while [[ -z "$__reply" ]]; do
      read -r -p "$__prompt: " __reply || fail "no input"
    done
  fi
  printf -v "$__var" '%s' "$__reply"
}

# ask_secret VAR "prompt": never echoed, never defaulted.
ask_secret() {
  local __var="$1" __prompt="$2" __reply=""
  while [[ -z "$__reply" ]]; do
    read -r -s -p "$__prompt: " __reply || fail "no input"
    printf '\n' >&2
  done
  printf -v "$__var" '%s' "$__reply"
}

# urlencode percent-encodes one URL component byte by byte.
urlencode() {
  local LC_ALL=C s="$1" out="" c i
  for (( i = 0; i < ${#s}; i++ )); do
    c="${s:i:1}"
    case "$c" in
      [a-zA-Z0-9.~_-]) out+="$c" ;;
      *) out+=$(printf '%%%02X' "'$c") ;;
    esac
  done
  printf '%s' "$out"
}

# quote single-quotes a value for the env file.
quote() { printf "'%s'" "${1//\'/\'\\\'\'}"; }

printf 'PostgreSQL (the role needs CREATE on the database; the tests create and drop throwaway schemas)\n'
ask pg_host "  host" "127.0.0.1"
ask pg_port "  port" "5432"
ask pg_db "  database" "examforge_test"
ask pg_user "  user" "examforge_test"
ask_secret pg_pass "  password (input hidden)"
ask pg_ssl "  sslmode (disable|require|verify-full)" "$([[ "$pg_host" == "127.0.0.1" || "$pg_host" == "localhost" ]] && echo disable || echo require)"

printf '\nSeaweedFS S3 (path-style; the bucket must already exist)\n'
ask s3_endpoint "  endpoint (http://host:8333)" "http://127.0.0.1:8333"
ask s3_bucket "  bucket" "examforge-test"
ask s3_region "  region (any string; SeaweedFS ignores it)" "us-east-1"
ask s3_key "  access key id" "any"
ask_secret s3_secret "  secret access key (input hidden)"

# ── Validate before writing anything ────────────────────────────────────────
[[ "$pg_host" =~ ^[A-Za-z0-9._:-]+$ ]] || fail "database host contains unexpected characters"
[[ "$pg_port" =~ ^[0-9]+$ ]] || fail "database port must be numeric"
[[ "$pg_db" =~ ^[A-Za-z0-9_-]+$ ]] || fail "database name must match [A-Za-z0-9_-]+"
[[ "$pg_ssl" =~ ^(disable|allow|prefer|require|verify-ca|verify-full)$ ]] || fail "invalid sslmode: $pg_ssl"
case "$s3_endpoint" in
  http://*|https://*) ;;
  *) fail "S3 endpoint must start with http:// or https://" ;;
esac
[[ "$s3_bucket" =~ ^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$ ]] || fail "S3 bucket must match the S3 naming rule"
[[ "$s3_region" =~ ^[A-Za-z0-9-]+$ ]] || fail "S3 region must match [A-Za-z0-9-]+"

db_url="postgres://$(urlencode "$pg_user"):$(urlencode "$pg_pass")@${pg_host}:${pg_port}/${pg_db}?sslmode=${pg_ssl}"

# ── Write with 0600 from the first byte ─────────────────────────────────────
umask 077
tmp="$(mktemp "${out}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
  printf '# Generated by scripts/setup-integration-env.sh on %s.\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf '# Local only: never commit, never paste into a ticket or chat.\n'
  printf 'export EXAMFORGE_TEST_DATABASE_URL=%s\n' "$(quote "$db_url")"
  printf 'export EXAMFORGE_TEST_S3_ENDPOINT=%s\n' "$(quote "$s3_endpoint")"
  printf 'export EXAMFORGE_TEST_S3_BUCKET=%s\n' "$(quote "$s3_bucket")"
  printf 'export EXAMFORGE_TEST_S3_REGION=%s\n' "$(quote "$s3_region")"
  printf 'export EXAMFORGE_TEST_S3_ACCESS_KEY_ID=%s\n' "$(quote "$s3_key")"
  printf 'export EXAMFORGE_TEST_S3_SECRET_ACCESS_KEY=%s\n' "$(quote "$s3_secret")"
  printf 'export EXAMFORGE_TEST_S3_FORCE_PATH_STYLE=true\n'
} >"$tmp"
mv -f "$tmp" "$out"
trap - EXIT
chmod 600 "$out"

# ── Masked summary + TCP reachability (no credentials shown) ────────────────
endpoint_hostport="${s3_endpoint#*://}"
endpoint_hostport="${endpoint_hostport%%/*}"
endpoint_host="${endpoint_hostport%%:*}"
endpoint_port="${endpoint_hostport##*:}"
[[ "$endpoint_port" == "$endpoint_host" ]] && endpoint_port=80

tcp_check() {
  local host="$1" port="$2" label="$3"
  if (exec 3<>"/dev/tcp/${host}/${port}") 2>/dev/null; then
    printf '  %-6s %s:%s reachable\n' "$label" "$host" "$port"
  else
    printf '  %-6s %s:%s NOT reachable\n' "$label" "$host" "$port"
  fi
}

printf '\nwrote %s (mode 600)\n' "$out"
printf '  postgres  %s@%s:%s/%s sslmode=%s\n' "$pg_user" "$pg_host" "$pg_port" "$pg_db" "$pg_ssl"
printf '  s3        %s bucket=%s region=%s\n' "$s3_endpoint" "$s3_bucket" "$s3_region"
printf '  reachability:\n'
tcp_check "$pg_host" "$pg_port" postgres
tcp_check "$endpoint_host" "$endpoint_port" s3

cat <<EOF

Next steps (run on a host that can reach both services):
  1. Validate the file without running tests:
       ./scripts/verify-integration.sh --env-file $out --check-only
  2. Run the real integration gate:
       ./scripts/verify-integration.sh --env-file $out

Provisioning reminders (only if not done yet):
  - Role privileges: the role needs CREATE on the database because each test
    creates and drops its own schema. As an admin:
      CREATE ROLE $pg_user LOGIN PASSWORD '<the password you just entered>';
      CREATE DATABASE $pg_db OWNER $pg_user;
    With an existing database: GRANT CREATE ON DATABASE $pg_db TO $pg_user;
  - Bucket: create "$s3_bucket" once, for example
      AWS_ACCESS_KEY_ID=... AWS_SECRET_ACCESS_KEY=... \\
        aws --endpoint-url $s3_endpoint s3 mb s3://$s3_bucket
    or, on the SeaweedFS host, in \`weed shell\`: s3.bucket.create -name $s3_bucket
  - The gate runs \`go test -race\`, which needs a C compiler (gcc). Without
    one, install build-essential or run the tests manually without -race.
  - Typst 0.15.x must be on PATH; the render test compiles a real PDF.
EOF
